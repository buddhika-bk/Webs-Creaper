import fs from 'node:fs';
import path from 'node:path';
import ExcelJS from 'exceljs';
import { Worker } from 'bullmq';
import { env } from '../config/env';
import { logger } from '../config/logger';
import { one, parseJson, run } from '../db/pool';
import { countSelection, fetchExportBatch, Selection } from '../modules/exports/export.query';
import { redisOptions } from '../queue/connection';
import { EXPORT_QUEUE, ExportJobData } from '../queue/queues';
import { adapters } from '../sources/registry';
import { EXPORT_COLUMNS, toExportValues } from '../modules/exports/export.format';

async function processExport(exportId: string) {
  const ex = await one<any>('SELECT * FROM exports WHERE id = ?', [exportId]);
  if (!ex || !['QUEUED', 'RUNNING'].includes(ex.status)) return;
  await run("UPDATE exports SET status = 'RUNNING', progress = 0, error_message = NULL WHERE id = ?", [exportId]);

  const selection = parseJson<Selection>(ex.selection, { mode: 'ids', ids: [] });
  const total = await countSelection(ex.workspace_id, selection);
  fs.mkdirSync(env.EXPORT_DIR, { recursive: true });
  const relName = `${exportId}.xlsx`;
  const filePath = path.join(env.EXPORT_DIR, relName);

  try {
    const wb = new ExcelJS.stream.xlsx.WorkbookWriter({ filename: filePath, useStyles: true, useSharedStrings: true });
    wb.creator = 'WebPoint Lead Platform';
    wb.created = new Date();
    const ws = wb.addWorksheet('Leads', { views: [{ state: 'frozen', ySplit: 1 }] });
    ws.columns = EXPORT_COLUMNS.map((c) => ({ width: c.width }));
    const header = ws.addRow(EXPORT_COLUMNS.map((c) => c.header));
    header.eachCell((cell) => {
      cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F4FD8' } };
      cell.alignment = { vertical: 'middle' };
    });
    header.commit();
    ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: EXPORT_COLUMNS.length } };

    let cursor = '00000000-0000-0000-0000-000000000000';
    let written = 0;
    const sourcesSeen = new Set<string>();
    for (;;) {
      const batch = await fetchExportBatch(ex.workspace_id, selection, cursor, 1000);
      if (!batch.length) break;
      for (const r of batch) {
        const row = ws.addRow(toExportValues(r));
        row.getCell(14).numFmt = 'yyyy-mm-dd hh:mm';
        row.commit();
        r.sources?.split(', ').forEach((s) => sourcesSeen.add(s));
      }
      written += batch.length;
      cursor = batch[batch.length - 1].id;
      await run('UPDATE exports SET progress = ?, row_count = ? WHERE id = ?', [total ? Math.min(99, Math.round((written / total) * 100)) : 99, written, exportId]);
    }
    ws.commit();

    // Attribution / provenance sheet: keeps source-specific attribution with the data.
    const about = wb.addWorksheet('About this export');
    about.columns = [{ width: 28 }, { width: 90 }];
    [
      ['Generated by', 'WebPoint Lead Platform'],
      ['Generated at (UTC)', new Date().toISOString()],
      ['Rows', written],
      ['Notes', 'Missing values are intentionally blank. Nothing was guessed or generated. Data freshness is shown in the Last Checked column.'],
      ...adapters.filter((a) => sourcesSeen.has(a.id)).map((a) => [`Attribution: ${a.label}`, `${a.compliance.attribution} - terms: ${a.compliance.termsUrl}`]),
    ].forEach((r) => about.addRow(r.map(safeCell)).commit());
    about.commit();
    await wb.commit();

    const stat = fs.statSync(filePath);
    const fileName = `webpoint-leads-${new Date().toISOString().slice(0, 10)}.xlsx`;
    await run(
      `UPDATE exports SET status = 'COMPLETED', progress = 100, row_count = ?, file_name = ?, file_path = ?, file_size = ?,
         completed_at = UTC_TIMESTAMP(3), expires_at = DATE_ADD(UTC_TIMESTAMP(3), INTERVAL ? HOUR) WHERE id = ?`,
      [written, fileName, relName, stat.size, env.EXPORT_TTL_HOURS, exportId],
    );
  } catch (err) {
    fs.rmSync(filePath, { force: true });
    logger.error({ err, exportId }, 'export failed');
    await run("UPDATE exports SET status = 'FAILED', error_message = ? WHERE id = ?", [(err as Error).message.slice(0, 300), exportId]);
    throw err;
  }
}

export function startExportWorker() {
  return new Worker<ExportJobData>(EXPORT_QUEUE, (job) => processExport(job.data.exportId), { connection: redisOptions(), concurrency: 1 });
}
